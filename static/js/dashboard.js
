/* ══════════════════════════════════════════════════════
   RORI HOTEL — HOUSEKEEPING DASHBOARD CHARTS
   ══════════════════════════════════════════════════════ */
(function () {
  'use strict';

  function init() {
    // ─── Sidebar toggle ───
    var toggle   = document.getElementById('hk-toggle');
    var sidebar  = document.getElementById('hk-sidebar');
    var backdrop = document.getElementById('hk-backdrop');
    if (toggle && sidebar) {
      toggle.addEventListener('click', function () {
        sidebar.classList.toggle('open');
        if (backdrop) backdrop.classList.toggle('show');
      });
    }
    if (backdrop && sidebar) {
      backdrop.addEventListener('click', function () {
        sidebar.classList.remove('open');
        backdrop.classList.remove('show');
      });
    }

    // ─── Charts ───
    if (typeof Chart === 'undefined') {
      console.warn('Chart.js not loaded');
      return;
    }

    var DATA = window.HK_DATA || {};

    Chart.defaults.color = '#9CA3AF';
    Chart.defaults.borderColor = 'rgba(212,175,55,0.10)';
    Chart.defaults.font.family = "'Inter', system-ui, sans-serif";
    Chart.defaults.font.size = 10;

    var TOOLTIP = {
      backgroundColor: 'rgba(8,8,18,0.97)',
      borderColor: 'rgba(212,175,55,0.4)',
      borderWidth: 1,
      titleColor: '#fff',
      bodyColor: '#e5e7eb',
      padding: 10,
      cornerRadius: 8,
      titleFont: { size: 11, weight: '700' },
      bodyFont: { size: 11 }
    };

    var GOLD = '#D4AF37';
    var BLUE = '#38BDF8';
    var PINK = '#EC4899';
    var GREEN = '#22C55E';
    var ORANGE = '#F59E0B';

    function grad(ctx, c1, c2) {
      var g = ctx.createLinearGradient(0, 0, 0, 320);
      g.addColorStop(0, c1);
      g.addColorStop(1, c2);
      return g;
    }

    function empty(el, icon, msg) {
      if (!el || !el.parentElement) return;
      el.parentElement.innerHTML =
        '<div class="hk-empty"><i class="fas ' + icon + '"></i>' + msg + '</div>';
    }

    // ─── TRENDS (Line) ───
    (function () {
      var el = document.getElementById('chart-trends');
      if (!el) return;
      var t = DATA.trends;
      if (!t || !t.labels || !t.labels.length) {
        empty(el, 'fa-chart-line', 'No data yet.');
        return;
      }
      var ctx = el.getContext('2d');
      new Chart(ctx, {
        type: 'line',
        data: {
          labels: t.labels,
          datasets: [
            {
              label: 'Total', data: t.total,
              borderColor: GOLD,
              backgroundColor: grad(ctx, 'rgba(212,175,55,0.30)', 'rgba(212,175,55,0.01)'),
              fill: true, tension: 0.4, borderWidth: 2.5,
              pointRadius: 0, pointHoverRadius: 5
            },
            {
              label: 'Completed', data: t.completed,
              borderColor: GREEN, backgroundColor: 'transparent',
              fill: false, tension: 0.4, borderWidth: 2,
              pointRadius: 0, pointHoverRadius: 4
            },
            {
              label: 'Pending', data: t.pending,
              borderColor: PINK, backgroundColor: 'transparent',
              fill: false, tension: 0.4, borderWidth: 2,
              pointRadius: 0, pointHoverRadius: 4
            },
            {
              label: 'In Progress', data: t.in_progress,
              borderColor: BLUE, backgroundColor: 'transparent',
              fill: false, tension: 0.4, borderWidth: 2,
              pointRadius: 0, pointHoverRadius: 4
            }
          ]
        },
        options: {
          responsive: true, maintainAspectRatio: false,
          interaction: { intersect: false, mode: 'index' },
          plugins: {
            legend: {
              position: 'top', align: 'end',
              labels: {
                boxWidth: 7, boxHeight: 7, padding: 14,
                usePointStyle: true, pointStyle: 'circle',
                font: { size: 11, weight: '600' }
              }
            },
            tooltip: TOOLTIP
          },
          scales: {
            x: {
              grid: { color: 'rgba(212,175,55,0.05)' },
              ticks: { maxRotation: 0, autoSkip: true, maxTicksLimit: 10 }
            },
            y: {
              beginAtZero: true,
              grid: { color: 'rgba(212,175,55,0.06)' },
              ticks: { precision: 0 }
            }
          }
        }
      });
    })();

    // ─── STATUS DONUT ───
    (function () {
      var el = document.getElementById('chart-status');
      if (!el) return;
      var s = DATA.statuses;
      if (!s || !s.labels || !s.labels.length) {
        empty(el, 'fa-circle-notch', 'No status data.');
        return;
      }
      var map = {
        'Pending': '#F59E0B', 'Approved': '#3B82F6',
        'In Progress': '#38BDF8', 'Completed': '#22C55E',
        'Closed': '#16A34A', 'Rejected': '#EF4444'
      };
      var colors = s.labels.map(function (l) { return map[l] || '#9CA3AF'; });
      new Chart(el.getContext('2d'), {
        type: 'doughnut',
        data: {
          labels: s.labels,
          datasets: [{
            data: s.values,
            backgroundColor: colors,
            borderColor: '#15152A',
            borderWidth: 2,
            hoverOffset: 8
          }]
        },
        options: {
          responsive: true, maintainAspectRatio: false,
          cutout: '66%',
          plugins: {
            legend: {
              position: 'right',
              labels: {
                boxWidth: 8, boxHeight: 8, padding: 8,
                usePointStyle: true, pointStyle: 'circle',
                font: { size: 10, weight: '600' }
              }
            },
            tooltip: {
              backgroundColor: TOOLTIP.backgroundColor,
              borderColor: TOOLTIP.borderColor,
              borderWidth: 1,
              titleColor: '#fff', bodyColor: '#e5e7eb',
              padding: 10, cornerRadius: 8,
              callbacks: {
                label: function (ctx) {
                  var total = s.values.reduce(function (a, b) { return a + b; }, 0);
                  var pct = total ? Math.round(ctx.parsed / total * 100) : 0;
                  return ' ' + ctx.label + ': ' + ctx.parsed + ' (' + pct + '%)';
                }
              }
            }
          }
        }
      });
    })();

    // ─── FLOORS (bar) ───
    (function () {
      var el = document.getElementById('chart-floors');
      if (!el) return;
      var f = DATA.floors;
      if (!f || !f.labels || !f.labels.length) {
        empty(el, 'fa-building', 'No floor data.');
        return;
      }
      var ctx = el.getContext('2d');
      new Chart(ctx, {
        type: 'bar',
        data: {
          labels: f.labels,
          datasets: [{
            label: 'Requests',
            data: f.values,
            backgroundColor: grad(ctx, 'rgba(212,175,55,0.9)', 'rgba(212,175,55,0.25)'),
            borderRadius: 6,
            borderSkipped: false,
            maxBarThickness: 34
          }]
        },
        options: {
          responsive: true, maintainAspectRatio: false,
          plugins: { legend: { display: false }, tooltip: TOOLTIP },
          scales: {
            x: {
              grid: { display: false },
              ticks: { font: { size: 10, weight: '600' } }
            },
            y: {
              beginAtZero: true,
              grid: { color: 'rgba(212,175,55,0.06)' },
              ticks: { precision: 0 }
            }
          }
        }
      });
    })();

    // ─── CATEGORIES DONUT ───
    (function () {
      var el = document.getElementById('chart-categories');
      if (!el) return;
      var c = DATA.categories;
      if (!c || !c.labels || !c.labels.length) {
        empty(el, 'fa-chart-pie', 'No category data.');
        return;
      }
      var palette = ['#D4AF37', '#E6C65C', '#38BDF8', '#22C55E', '#F59E0B',
                     '#EC4899', '#8B5CF6', '#06B6D4', '#F472B6', '#10B981'];
      new Chart(el.getContext('2d'), {
        type: 'doughnut',
        data: {
          labels: c.labels,
          datasets: [{
            data: c.values,
            backgroundColor: palette,
            borderColor: '#15152A',
            borderWidth: 2,
            hoverOffset: 8
          }]
        },
        options: {
          responsive: true, maintainAspectRatio: false,
          cutout: '66%',
          plugins: {
            legend: {
              position: 'right',
              labels: {
                boxWidth: 8, boxHeight: 8, padding: 8,
                usePointStyle: true, pointStyle: 'circle',
                font: { size: 10, weight: '600' }
              }
            },
            tooltip: {
              backgroundColor: TOOLTIP.backgroundColor,
              borderColor: TOOLTIP.borderColor,
              borderWidth: 1,
              titleColor: '#fff', bodyColor: '#e5e7eb',
              padding: 10, cornerRadius: 8
            }
          }
        }
      });
    })();

    // ─── PRIORITIES DONUT ───
    (function () {
      var el = document.getElementById('chart-priorities');
      if (!el) return;
      var p = DATA.priorities;
      if (!p || !p.labels || !p.labels.length) {
        empty(el, 'fa-fire', 'No priority data.');
        return;
      }
      var map = {
        'URGENT': '#EF4444',
        'HIGH':   '#F59E0B',
        'MEDIUM': '#38BDF8',
        'LOW':    '#22C55E'
      };
      var colors = p.labels.map(function (l) { return map[l] || '#9CA3AF'; });
      new Chart(el.getContext('2d'), {
        type: 'doughnut',
        data: {
          labels: p.labels,
          datasets: [{
            data: p.values,
            backgroundColor: colors,
            borderColor: '#15152A',
            borderWidth: 2,
            hoverOffset: 8
          }]
        },
        options: {
          responsive: true, maintainAspectRatio: false,
          cutout: '66%',
          plugins: {
            legend: {
              position: 'right',
              labels: {
                boxWidth: 8, boxHeight: 8, padding: 8,
                usePointStyle: true, pointStyle: 'circle',
                font: { size: 10, weight: '600' }
              }
            },
            tooltip: {
              backgroundColor: TOOLTIP.backgroundColor,
              borderColor: TOOLTIP.borderColor,
              borderWidth: 1,
              titleColor: '#fff', bodyColor: '#e5e7eb',
              padding: 10, cornerRadius: 8
            }
          }
        }
      });
    })();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();