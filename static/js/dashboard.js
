(function () {
  'use strict';

  function init() {
    if (typeof Chart === 'undefined') {
      console.warn('Chart.js not loaded');
      return;
    }

    const DATA = window.RORI_DATA || {};

    Chart.defaults.color = '#9CA3AF';
    Chart.defaults.borderColor = 'rgba(212,175,55,0.12)';
    Chart.defaults.font.family = "'Inter', system-ui, sans-serif";
    Chart.defaults.font.size = 11;

    const tooltip = {
      backgroundColor: 'rgba(8,8,18,0.96)',
      borderColor: 'rgba(212,175,55,0.4)',
      borderWidth: 1,
      titleColor: '#fff',
      bodyColor: '#e5e7eb',
      padding: 12,
      cornerRadius: 10,
    };

    const GOLD = '#D4AF37';
    const GOLD_LIGHT = '#E6C65C';
    const BLUE = '#38BDF8';
    const PINK = '#EC4899';
    const GREEN = '#22C55E';

    function grad(ctx, c1, c2) {
      const g = ctx.createLinearGradient(0, 0, 0, 320);
      g.addColorStop(0, c1);
      g.addColorStop(1, c2);
      return g;
    }

    function empty(el, icon, msg) {
      if (!el || !el.parentElement) return;
      el.parentElement.innerHTML =
        '<div class="rori-empty"><i class="fas ' + icon + '"></i>' + msg + '</div>';
    }

    /* TRENDS */
    (function () {
      const el = document.getElementById('chart-trends');
      if (!el) return;
      const t = DATA.trends;
      if (!t || !t.labels || !t.labels.length) {
        empty(el, 'fa-chart-line', 'No data for the selected filters.');
        return;
      }
      const ctx = el.getContext('2d');
      new Chart(ctx, {
        type: 'line',
        data: {
          labels: t.labels,
          datasets: [
            {
              label: 'Total',
              data: t.total,
              borderColor: GOLD,
              backgroundColor: grad(ctx, 'rgba(212,175,55,0.35)', 'rgba(212,175,55,0.02)'),
              fill: true, tension: 0.4, borderWidth: 2.5,
              pointRadius: 0, pointHoverRadius: 5,
            },
            {
              label: 'Completed',
              data: t.completed,
              borderColor: GREEN, backgroundColor: 'transparent',
              fill: false, tension: 0.4, borderWidth: 2, pointRadius: 0,
            },
            {
              label: 'Pending',
              data: t.pending,
              borderColor: PINK, backgroundColor: 'transparent',
              fill: false, tension: 0.4, borderWidth: 2, pointRadius: 0,
            },
            {
              label: 'In Progress',
              data: t.in_progress,
              borderColor: BLUE, backgroundColor: 'transparent',
              fill: false, tension: 0.4, borderWidth: 2, pointRadius: 0,
            },
          ],
        },
        options: {
          responsive: true, maintainAspectRatio: false,
          interaction: { intersect: false, mode: 'index' },
          plugins: {
            legend: { position: 'top', align: 'end', labels: { boxWidth: 8, boxHeight: 8, padding: 15, usePointStyle: true, pointStyle: 'circle' } },
            tooltip: tooltip,
          },
          scales: {
            x: { grid: { color: 'rgba(212,175,55,0.05)' }, ticks: { maxRotation: 0, autoSkip: true, maxTicksLimit: 10 } },
            y: { beginAtZero: true, grid: { color: 'rgba(212,175,55,0.06)' }, ticks: { precision: 0 } },
          },
        },
      });
    })();

    /* CATEGORIES */
    (function () {
      const el = document.getElementById('chart-categories');
      if (!el) return;
      const c = DATA.categories;
      if (!c || !c.labels || !c.labels.length) {
        empty(el, 'fa-chart-pie', 'No category data available.');
        return;
      }
      const palette = ['#D4AF37','#E6C65C','#38BDF8','#22C55E','#F59E0B','#EC4899','#8B5CF6','#06B6D4','#F472B6','#10B981'];
      new Chart(el.getContext('2d'), {
        type: 'doughnut',
        data: {
          labels: c.labels,
          datasets: [{ data: c.values, backgroundColor: palette, borderColor: '#15152A', borderWidth: 3, hoverOffset: 10 }],
        },
        options: {
          responsive: true, maintainAspectRatio: false, cutout: '68%',
          plugins: {
            legend: { position: 'right', labels: { boxWidth: 8, boxHeight: 8, padding: 10, usePointStyle: true, pointStyle: 'circle', font: { size: 10 } } },
            tooltip: { ...tooltip, callbacks: { label: function (ctx) {
              const pct = c.percentages[ctx.dataIndex];
              return ' ' + ctx.label + ': ' + ctx.parsed + ' (' + pct + '%)';
            } } },
          },
        },
      });
    })();

    /* STATUS */
    (function () {
      const el = document.getElementById('chart-status');
      if (!el) return;
      const s = DATA.statuses;
      if (!s || !s.labels || !s.labels.length) {
        empty(el, 'fa-chart-pie', 'No status data available.');
        return;
      }
      const map = { 'Pending':'#F59E0B','Approved':'#3B82F6','Assigned':'#D4AF37','In Progress':'#38BDF8','Completed':'#22C55E','Verified':'#10B981','Closed':'#16A34A','Rejected':'#EF4444','Overdue':'#DC2626' };
      const colors = s.labels.map(l => map[l] || '#9CA3AF');
      new Chart(el.getContext('2d'), {
        type: 'doughnut',
        data: {
          labels: s.labels,
          datasets: [{ data: s.values, backgroundColor: colors, borderColor: '#15152A', borderWidth: 3, hoverOffset: 10 }],
        },
        options: {
          responsive: true, maintainAspectRatio: false, cutout: '68%',
          plugins: {
            legend: { position: 'right', labels: { boxWidth: 8, boxHeight: 8, padding: 10, usePointStyle: true, pointStyle: 'circle', font: { size: 10 } } },
            tooltip: { ...tooltip, callbacks: { label: function (ctx) {
              const pct = s.percentages[ctx.dataIndex];
              return ' ' + ctx.label + ': ' + ctx.parsed + ' (' + pct + '%)';
            } } },
          },
        },
      });
    })();

    /* DEPARTMENTS */
    (function () {
      const el = document.getElementById('chart-departments');
      if (!el) return;
      const d = DATA.departments;
      if (!d || !d.labels || !d.labels.length) {
        empty(el, 'fa-chart-bar', 'No department data available.');
        return;
      }
      const ctx = el.getContext('2d');
      new Chart(ctx, {
        type: 'bar',
        data: {
          labels: d.labels,
          datasets: [{ label: 'Requests', data: d.values,
            backgroundColor: grad(ctx, 'rgba(212,175,55,0.9)', 'rgba(212,175,55,0.3)'),
            borderRadius: 8, borderSkipped: false, maxBarThickness: 34 }],
        },
        options: {
          indexAxis: 'y', responsive: true, maintainAspectRatio: false,
          plugins: { legend: { display: false }, tooltip: tooltip },
          scales: {
            x: { beginAtZero: true, grid: { color: 'rgba(212,175,55,0.06)' }, ticks: { precision: 0 } },
            y: { grid: { display: false }, ticks: { font: { size: 11 } } },
          },
        },
      });
    })();

    /* SIDEBAR */
    const toggle = document.getElementById('sidebar-toggle');
    const sidebar = document.getElementById('rori-sidebar');
    const backdrop = document.getElementById('sidebar-backdrop');
    if (toggle && sidebar) {
      toggle.addEventListener('click', function () {
        sidebar.classList.toggle('open');
        if (backdrop) backdrop.classList.toggle('show');
      });
    }
    if (backdrop && sidebar) {
      backdrop.addEventListener('click', function () {
        sidebar.classList.remove('open');
        backdrop.classList.remove('show');
      });
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();